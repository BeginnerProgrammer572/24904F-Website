// Run locally with `npm run photos`: copies reference/images into assets/photos,
// capped at 2000 px with metadata stripped. Vercel never sees reference/.
import { mkdir, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const SRC = "reference/images";
const OUT = "assets/photos";
// Not used by the site: an unused duplicate shot, the old QR code, and the
// gear-train close-up, which was removed on purpose (see docs/BRIEF.md).
const SKIP = new Set(["pushback-build.jpg", "media-qr.png", "gears.jpg"]);

const camel = (name) => name.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());

for (const dir of [OUT, "app", "content"]) await mkdir(dir, { recursive: true });
const files = (await readdir(SRC)).filter((f) => !SKIP.has(f)).sort();

for (const file of files) {
  const image = sharp(path.join(SRC, file))
    .rotate()
    .resize({ width: 2000, height: 2000, fit: "inside", withoutEnlargement: true });
  if (file.endsWith(".png")) image.png({ compressionLevel: 9 });
  else image.jpeg({ quality: 82, mozjpeg: true });
  await image.toFile(path.join(OUT, file));
}

await sharp(path.join(SRC, "team-logo.jpg"))
  .resize(192, 192, { fit: "contain", background: "#fff" })
  .png()
  .toFile("app/icon.png");

// Social preview image (Next.js picks it up by its file name).
await sharp(path.join(SRC, "team-photo.jpg"))
  .resize(1200, 630, { fit: "cover" })
  .jpeg({ quality: 82, mozjpeg: true })
  .toFile("app/opengraph-image.jpg");

// Static imports give next/image the dimensions, so there is no layout shift.
// Listing the output folder keeps files added there directly (trojan-horse.png).
const outputs = (await readdir(OUT)).sort();
const names = outputs.map((f) => camel(path.parse(f).name));
await writeFile(
  "content/photos.js",
  [
    "// Generated by scripts/prepare-photos.mjs.",
    ...outputs.map((f, i) => `import ${names[i]} from "@/assets/photos/${f}";`),
    "",
    "export const photos = {",
    ...names.map((n) => `  ${n},`),
    "};",
    "",
  ].join("\n"),
);
console.log(`${files.length} photos written to ${OUT}`);
